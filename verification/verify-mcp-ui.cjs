"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(process.env.WAKEMATE_PLAYWRIGHT_PATH || "playwright");

async function run() {
  const browser = await chromium.launch({ headless: true });
  const failures = [];
  const checks = [];
  const base = process.env.WAKEMATE_UI_QA_URL || "http://127.0.0.1:18091";
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  page.on("pageerror", error => failures.push(error.message));
  const clickAction = name => page.locator(`[data-action="${name}"]`).first().click();
  const dialog = page.locator("#action-dialog");
  const submit = () => dialog.locator("button[type=submit]").click();
  const waitClosed = () => dialog.waitFor({ state: "hidden" });
  const endpoint = "wss://api.xiaozhi.me/mcp/?token=qa-local-only-never-use-in-production";
  try {
    await page.goto(base + "/admin#mcp");
    await page.locator('#login-form [name="username"]').fill("admin");
    await page.locator('#login-form [name="password"]').fill("Qa-admin-password-2026");
    await page.locator("#login-form button").click();
    await page.locator('[data-action="create-binding"]').waitFor();
    assert.equal(await page.locator('[data-action="create-binding"]').isEnabled(), true);
    await clickAction("create-binding");
    await dialog.waitFor();
    assert.match(await dialog.innerText(), /患者/);
    checks.push("Empty patient state explains the prerequisite and keeps the action usable");
    await dialog.locator('[data-action="create-mcp-patient"]').click();
    await dialog.locator('[name="display_name"]').fill("QA patient (isolated schema)");
    await dialog.locator('[name="phone"]').fill("19900000001");
    await dialog.locator('[name="password"]').fill("Qa-patient-password-2026");
    await submit();
    await waitClosed();
    await page.locator('[data-view="patients"]').click();
    await page.locator('[data-action="edit-user"]').first().waitFor();
    await page.locator('[data-action="edit-user"]').first().click();
    await dialog.waitFor();
    assert.equal(await dialog.locator('[name="phone"]').isDisabled(), true);
    assert.equal(await dialog.locator('[name="role"]').isDisabled(), true);
    await dialog.locator('[name="display_name"]').fill("QA patient edited");
    await dialog.locator('[name="timezone"]').fill("Invalid/Timezone");
    await submit();
    await dialog.locator("#dialog-error").waitFor();
    assert.equal(await dialog.locator('[name="display_name"]').inputValue(), "QA patient edited");
    assert.equal(await dialog.locator("button[type=submit]").isEnabled(), true);
    await dialog.locator('[name="timezone"]').fill("UTC");
    await page.screenshot({ path: path.join(__dirname, "patient-edit-desktop.png"), fullPage: true });
    await submit();
    await waitClosed();
    await page.locator('[data-view="mcp"]').click();
    await page.locator('[data-action="create-binding"]').first().waitFor();
    checks.push("Admin patient edit handles validation recovery and updates display name/timezone; phone and role stay read-only");
    await clickAction("create-binding");
    const patients = dialog.locator('[name="patient_id"] option');
    await patients.nth(1).waitFor({ state: "attached" });
    assert.match(await patients.nth(1).innerText(), /QA patient edited/);
    const patientId = await patients.nth(1).getAttribute("value");
    await dialog.locator('[name="patient_id"]').selectOption(patientId);
    await dialog.locator('[name="label"]').fill("QA XiaoZhi");
    const field = dialog.locator('[name="endpoint"]');
    assert.equal(await field.getAttribute("type"), "password");
    await field.fill("wss://127.0.0.1/mcp/?token=invalid-private-destination");
    await submit();
    await dialog.locator("#dialog-error").waitFor();
    assert.doesNotMatch(await dialog.locator("#dialog-error").innerText(), /invalid-private-destination/);
    assert.equal(await dialog.locator("button[type=submit]").isEnabled(), true);
    await field.fill(endpoint);
    await submit();
    await waitClosed();
    await page.getByText("QA XiaoZhi", { exact: false }).first().waitFor();
    assert.equal(await page.locator('[name="endpoint"]').count(), 0);
    assert.doesNotMatch(await page.locator("#view").innerText(), /qa-local-only-never-use/);
    checks.push("Real patient and encrypted endpoint configuration save; invalid destination is recoverable");
    await clickAction("configure-binding");
    await dialog.waitFor();
    assert.equal(await dialog.locator('[name="endpoint"]').inputValue(), "");
    await dialog.locator('[name="endpoint"]').fill(endpoint + "-updated");
    await submit();
    await waitClosed();
    checks.push("Endpoint update does not reveal the stored credential");
    await page.screenshot({ path: path.join(__dirname, "mcp-desktop.png"), fullPage: true });
    await clickAction("stop-binding");
    await dialog.waitFor();
    await submit();
    await waitClosed();
    await page.locator('[data-action="configure-binding"]').first().waitFor();
    checks.push("Disconnect action clears the real configuration");
    await clickAction("revoke-binding");
    await dialog.waitFor();
    await submit();
    await waitClosed();
    assert.equal(await page.locator('[data-action="revoke-binding"]').first().isEnabled(), false);
    checks.push("Revoked binding cannot be reconnected");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator("#refresh").click();
    await page.locator('[data-action="create-binding"]').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await clickAction("create-binding");
    await dialog.waitFor();
    assert.equal(await dialog.locator('[name="endpoint"]').inputValue(), "");
    await dialog.locator('[name="endpoint"]').focus();
    assert.equal(await dialog.locator('[name="endpoint"]').evaluate(el => el === document.activeElement), true);
    await page.screenshot({ path: path.join(__dirname, "mcp-mobile.png"), fullPage: true });
    await page.keyboard.press("Escape");
    await waitClosed();
    await page.locator('[name="endpoint"]').waitFor({ state: "detached" });
    assert.equal(await page.locator('[name="endpoint"]').count(), 0);
    checks.push("Mobile width, focus, Escape and credential field cleanup pass");
    await page.locator("#menu-toggle").click();
    await page.locator('[data-view="patients"]').click();
    await page.locator('[data-action="edit-user"]').first().click();
    await dialog.waitFor();
    assert.equal(await dialog.locator('[name="display_name"]').inputValue(), "QA patient edited");
    assert.equal(await dialog.locator('[name="timezone"]').inputValue(), "UTC");
    await dialog.locator('[name="display_name"]').focus();
    assert.equal(await dialog.locator('[name="display_name"]').evaluate(el => el === document.activeElement), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(__dirname, "patient-edit-mobile.png"), fullPage: true });
    await page.keyboard.press("Escape");
    await waitClosed();
    checks.push("Patient edit remains keyboard-accessible without page overflow at 390px");
    assert.deepEqual(failures, []);
    const report = { result: "passed", database: "isolated temporary PostgreSQL schema", checks };
    fs.writeFileSync(path.join(__dirname, "mcp-ui-verification.json"), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally {
    await browser.close();
  }
}

run().catch(error => { console.error(error.stack); process.exitCode = 1; });
